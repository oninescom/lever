const (
	BlockStart = "# === Lever Linux Tools Autoload Start ==="
	BlockEnd   = "# === Lever Linux Tools Autoload End ==="
	shimMarker = "@rem Generated by Lever; do not edit"
	stateKey   = `Software\Lever`
)

var commandNamePattern = regexp.MustCompile(`^[a-zA-Z0-9_-]+$`)

func NewInstallCmd(rootCmd *engine.Command) *engine.Command {
	return &engine.Command{
		Use:   "install",
		Short: "将 Lever 命令安装到 PowerShell 和 CMD",
		Args:  utils.NoArgs,
		RunE: func(c *engine.Command, args []string) error {
			exePath, err := os.Executable()
			if err != nil {
				return fmt.Errorf("安装失败: %w", err)
			}
			exePath, err = filepath.Abs(exePath)
			if err != nil {
				return fmt.Errorf("安装失败: %w", err)
			}

			var names []string
			for _, child := range rootCmd.Children {
				name := engine.CommandName(child.Use)
				if name != "install" && name != "uninstall" {
					names = append(names, name)
				}
			}

			psOK := installPowerShell(exePath, names)
			cmdErr := installCMD(exePath, names)
			if cmdErr != nil {
				fmt.Fprintf(os.Stderr, "CMD 安装失败: %v\n", cmdErr)
			} else {
				fmt.Println("CMD 命令已安装；请重新打开终端。")
			}
			if psOK {
				fmt.Println("PowerShell 命令已安装；请重新打开终端。")
			}
			if !psOK && cmdErr != nil {
				return errors.New("PowerShell 和 CMD 安装均失败")
			}
			return nil
		},
	}
}

func installPowerShell(exePath string, names []string) bool {
	quotedExe := "'" + strings.ReplaceAll(exePath, "'", "''") + "'"
	var lines []string
	for _, name := range names {
		lines = append(lines,
			fmt.Sprintf("if (Get-Alias %s -ErrorAction SilentlyContinue) { Remove-Item alias:%s }", name, name),
			fmt.Sprintf("function %s { if ($MyInvocation.ExpectingInput) { $input | & %s %s @args } else { & %s %s @args } }", name, quotedExe, name, quotedExe, name),
		)
	}
	block := "\n" + BlockStart + "\n" + strings.Join(lines, "\n") + "\n" + BlockEnd + "\n"
	success := false
	for _, path := range getProfilePaths() {
		if err := utils.EditProfileFile(path, true, func(existing string) (string, error) {
			return upsertProfileBlock(existing, block)
		}); err != nil {
			fmt.Fprintf(os.Stderr, "PowerShell 配置写入失败 %s: %v\n", path, err)
		} else {
			success = true
		}
	}
	return success
}

func installCMD(exePath string, names []string) error {
	shimDir, err := getShimDir()
	if err != nil {
		return err
	}
	if err := os.MkdirAll(shimDir, 0755); err != nil {
		return err
	}
	for _, name := range names {
		if !commandNamePattern.MatchString(name) {
			return fmt.Errorf("无效命令名 %q", name)
		}
		path := filepath.Join(shimDir, name+".cmd")
		if err := writeShim(path, exePath, name); err != nil {
			return err
		}
	}
	if err := addUserPath(shimDir); err != nil {
		return err
	}
	return clearLegacyAutoRun(exePath)
}

func getShimDir() (string, error) {
	base := os.Getenv("LOCALAPPDATA")
	if base == "" {
		return "", errors.New("LOCALAPPDATA 未设置")
	}
	return filepath.Join(base, "Lever", "bin"), nil
}

func shimContent(exePath, name string) string {
	// Batch 文件中的百分号必须加倍，%* 则原样转发用户参数。
	escapedExe := strings.ReplaceAll(exePath, "%", "%%")
	return shimMarker + "\r\n@echo off\r\n@\"" + escapedExe + "\" " + name + " %*\r\n"
}

func writeShim(path, exePath, name string) error {
	old, err := os.ReadFile(path)
	if err == nil && !strings.HasPrefix(string(old), shimMarker+"\r\n") {
		return fmt.Errorf("不会覆盖已有文件 %s", path)
	}
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return os.WriteFile(path, []byte(shimContent(exePath, name)), 0644)
}

func samePath(a, b string) bool {
	a = strings.Trim(strings.TrimSpace(a), "\"")
	b = strings.Trim(strings.TrimSpace(b), "\"")
	return strings.EqualFold(filepath.Clean(os.ExpandEnv(a)), filepath.Clean(os.ExpandEnv(b)))
}

func pathContains(list, dir string) bool {
	for _, part := range filepath.SplitList(list) {
		if part != "" && samePath(part, dir) {
			return true
		}
	}
	return false
}

func setPathValue(key registry.Key, value string, kind uint32) error {
	if kind == registry.EXPAND_SZ {
		return key.SetExpandStringValue("Path", value)
	}
	return key.SetStringValue("Path", value)
}

func addUserPath(dir string) error {
	key, err := registry.OpenKey(registry.CURRENT_USER, `Environment`, registry.QUERY_VALUE|registry.SET_VALUE)
	if err != nil {
		return err
	}
	defer key.Close()
	current, kind, err := key.GetStringValue("Path")
	if err != nil && !errors.Is(err, registry.ErrNotExist) {
		return err
	}
	if pathContains(current, dir) {
		return nil
	}
	next := strings.TrimRight(current, ";")
	if next != "" {
		next += ";"
	}
	next += dir
	if err := setPathValue(key, next, kind); err != nil {
		return err
	}
	state, _, err := registry.CreateKey(registry.CURRENT_USER, stateKey, registry.SET_VALUE)
	if err == nil {
		err = state.SetStringValue("AddedShimPath", dir)
		state.Close()
	}
	if err != nil {
		_ = setPathValue(key, current, kind)
		return err
	}
	notifyEnvironmentChange()
	return nil
}

func notifyEnvironmentChange() {
	name, err := windows.UTF16PtrFromString("Environment")
	if err != nil {
		return
	}
	var result uintptr
	proc := windows.NewLazySystemDLL("user32.dll").NewProc("SendMessageTimeoutW")
	_, _, _ = proc.Call(0xffff, 0x001a, 0, uintptr(unsafe.Pointer(name)), 0x0002, 1000, uintptr(unsafe.Pointer(&result)))
	runtime.KeepAlive(name)
}

func clearLegacyAutoRun(exePath string) error {
	key, err := registry.OpenKey(registry.CURRENT_USER, `Software\Microsoft\Command Processor`, registry.QUERY_VALUE|registry.SET_VALUE)
	if errors.Is(err, registry.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	defer key.Close()
	value, _, err := key.GetStringValue("AutoRun")
	if errors.Is(err, registry.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if isLegacyAutoRun(value, exePath) {
		return key.DeleteValue("AutoRun")
	}
	return nil
}

func isLegacyAutoRun(value, exePath string) bool {
	legacy := filepath.Join(filepath.Dir(exePath), "cmd_init.bat")
	if samePath(value, legacy) {
		return true
	}
	path := os.ExpandEnv(strings.Trim(value, "\""))
	if !filepath.IsAbs(path) || !strings.EqualFold(filepath.Base(path), "cmd_init.bat") {
		return false
	}
	content, err := os.ReadFile(path)
	if err != nil {
		return false
	}
	lines := strings.Split(strings.ReplaceAll(string(content), "\r\n", "\n"), "\n")
	if len(lines) < 2 || lines[0] != "@echo off" {
		return false
	}
	seen := false
	for _, line := range lines[1:] {
		if line == "" {
			continue
		}
		if !strings.HasPrefix(line, "doskey ") || !strings.Contains(strings.ToLower(line), "lever.exe") || !strings.HasSuffix(line, " $*") {
			return false
		}
		seen = true
	}
	return seen
}

func NewUninstallCmd() *engine.Command {
	return &engine.Command{
		Use:   "uninstall",
		Short: "移除 Lever 的 PowerShell 和 CMD 命令入口",
		Args:  utils.NoArgs,
		RunE: func(c *engine.Command, args []string) error {
			var failed bool
			for _, path := range getProfilePaths() {
				err := utils.EditProfileFile(path, false, func(existing string) (string, error) {
					return removeProfileBlock(existing)
				})
				if err != nil {
					fmt.Fprintf(os.Stderr, "PowerShell 配置清理失败 %s: %v\n", path, err)
					failed = true
				}
			}
			if err := uninstallCMD(); err != nil {
				fmt.Fprintf(os.Stderr, "CMD 清理失败: %v\n", err)
				failed = true
			}
			if exePath, err := os.Executable(); err == nil {
				if err := clearLegacyAutoRun(exePath); err != nil {
					fmt.Fprintf(os.Stderr, "旧版 CMD 配置清理失败: %v\n", err)
					failed = true
				}
			}
			if !failed {
				fmt.Println("Lever 命令入口已移除；请重新打开终端。")
				return nil
			}
			return errors.New("部分 Lever 命令入口未能清理")
		},
	}
}

func uninstallCMD() error {
	dir, err := getShimDir()
	if err != nil {
		return err
	}
	entries, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		entries = nil
		err = nil
	}
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.EqualFold(filepath.Ext(entry.Name()), ".cmd") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if strings.HasPrefix(string(content), shimMarker+"\r\n") {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	state, err := registry.OpenKey(registry.CURRENT_USER, stateKey, registry.QUERY_VALUE|registry.SET_VALUE)
	if errors.Is(err, registry.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	defer state.Close()
	added, _, err := state.GetStringValue("AddedShimPath")
	if errors.Is(err, registry.ErrNotExist) || !samePath(added, dir) {
		return nil
	}
	if err != nil {
		return err
	}
	key, err := registry.OpenKey(registry.CURRENT_USER, `Environment`, registry.QUERY_VALUE|registry.SET_VALUE)
	if err != nil {
		return err
	}
	defer key.Close()
	current, kind, err := key.GetStringValue("Path")
	if err != nil {
		return err
	}
	var kept []string
	for _, part := range filepath.SplitList(current) {
		if part != "" && !samePath(part, dir) {
			kept = append(kept, part)
		}
	}
	if err := setPathValue(key, strings.Join(kept, ";"), kind); err != nil {
		return err
	}
	if err := state.DeleteValue("AddedShimPath"); err != nil {
		return err
	}
	notifyEnvironmentChange()
	return nil
}

func removeProfileBlock(existing string) (string, error) {
	start := strings.Index(existing, BlockStart)
	if start == -1 {
		return existing, nil
	}
	end := strings.Index(existing[start:], BlockEnd)
	if end == -1 {
		return "", errors.New("lever 配置块缺少结束标记")
	}
	return existing[:start] + existing[start+end+len(BlockEnd):], nil
}

func upsertProfileBlock(existing, block string) (string, error) {
	start := strings.Index(existing, BlockStart)
	if start == -1 {
		return existing + block, nil
	}
	end := strings.Index(existing[start:], BlockEnd)
	if end == -1 {
		return "", errors.New("lever 配置块缺少结束标记")
	}
	return existing[:start] + block + existing[start+end+len(BlockEnd):], nil
}

func getProfilePaths() []string {
	output, err := exec.Command("powershell.exe", "-NoProfile", "-NonInteractive", "-Command", "[Console]::OutputEncoding = [Text.Encoding]::UTF8; [Environment]::GetFolderPath('MyDocuments')").Output()
	if err != nil {
		return nil
	}
	documentsDir := strings.TrimSpace(string(output))
	if documentsDir == "" {
		return nil
	}
	return []string{
		filepath.Join(documentsDir, "WindowsPowerShell", "Microsoft.PowerShell_profile.ps1"),
		filepath.Join(documentsDir, "PowerShell", "Microsoft.PowerShell_profile.ps1"),
	}
}
